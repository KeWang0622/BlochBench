"""Builds reference/control workspaces and grades them (author validation helper, heldout-v7)."""
import json, os, shutil, subprocess, sys, time, platform
from pathlib import Path


def _env():
    e = dict(os.environ)
    for k in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS'):
        e[k] = '1'
    e['MPLBACKEND'] = 'Agg'
    return e


def build_ws(entry_name, entry_text, wsdir, pub_inputs, out_name, report_fn, extra_files=None):
    wsdir = Path(wsdir)
    wsdir.mkdir(parents=True, exist_ok=True)
    (wsdir / entry_name).write_text(entry_text)
    t = time.time()
    r = subprocess.run([sys.executable, entry_name, '--input-dir', str(pub_inputs), '--output', out_name],
                       cwd=wsdir, capture_output=True, text=True, env=_env(), timeout=3000)
    if r.returncode != 0:
        (wsdir / 'build_error.txt').write_text(r.stderr)
    rep = report_fn(wsdir / out_name) if (wsdir / out_name).exists() else {}
    rep.setdefault('limitations', ['synthetic data only'])
    rep['build_seconds'] = round(time.time() - t, 1)
    (wsdir / 'report.json').write_text(json.dumps(rep, indent=1, default=float) + '\n')
    (wsdir / 'README.md').write_text('# Author control workspace\n\nValidation: generated by the task author; see report.json.\n\nLimitations: synthetic data, author control.\n')
    (wsdir / 'environment.txt').write_text(f'python {platform.python_version()}\n')
    for name, txt in (extra_files or {}).items():
        (wsdir / name).write_text(txt)
    return r.returncode


def grade_ws(arm_script, wsdir, evdir):
    evdir = Path(evdir)
    if evdir.exists():
        dst = Path('/private/tmp') / ('v7old-' + evdir.name + '-' + str(int(time.time() * 1000)))
        shutil.move(str(evdir), str(dst))
    evdir.mkdir(parents=True)
    r = subprocess.run([sys.executable, str(arm_script), str(wsdir), str(evdir)], capture_output=True, text=True, env=_env(), timeout=7200)
    try:
        return json.loads((evdir / 'grade.json').read_text())
    except Exception:
        return {'all_automated_checks_pass': None, 'checks': {}, 'stderr': r.stderr[-2000:]}


def apply_subs(text, subs):
    for a, b in subs:
        if a not in text:
            raise ValueError('substitution anchor not found: ' + a)
        text = text.replace(a, b)
    return text


def run_all(here, entry_name, out_name, report_fn, controls, arm_script, only=None):
    here = Path(here)
    ref_text = (here / 'reference' / entry_name).read_text()
    pub_inputs = here.parent / 'public' / 'inputs'
    results = {}
    for c in controls:
        name = c['name']
        if only and name not in only:
            continue
        if c.get('entry_file'):
            text = (here / c['entry_file']).read_text()
        else:
            text = apply_subs(ref_text, c.get('subs', []))
        wsdir = here / 'controls' / name if name != 'reference' else here / 'reference_ws'
        if wsdir.exists():
            shutil.move(str(wsdir), str(Path('/private/tmp') / ('v7old-' + name + '-' + str(int(time.time() * 1000)))))
        t = time.time()
        rc = build_ws(entry_name, text, wsdir, pub_inputs, out_name, report_fn)
        g = grade_ws(arm_script, wsdir, here / 'validation' / 'eval' / name)
        failed = [k for k, v in g.get('checks', {}).items() if not v.get('pass')]
        if c['kind'] == 'positive':
            ok = g.get('all_automated_checks_pass') is True
        else:
            ok = (g.get('all_automated_checks_pass') is False) and any(f in failed for f in c['targets'])
        results[name] = {'kind': c['kind'], 'domain_correction_omission': c.get('domain', False), 'description': c.get('desc', ''),
                         'targets': c.get('targets', []), 'build_returncode': rc, 'all_pass': g.get('all_automated_checks_pass'),
                         'failed_checks': failed, 'expectation_met': ok, 'seconds': round(time.time() - t, 1),
                         'details': {k: v.get('detail') for k, v in g.get('checks', {}).items() if not k.startswith(('deliverables', 'report', 'environment', 'readme'))}}
        print(name, 'expectation_met=', ok, 'failed=', failed, flush=True)
    out = here / 'validation' / 'summary.json'
    old = json.loads(out.read_text()) if out.exists() else {}
    old.update(results)
    out.write_text(json.dumps(old, indent=1, default=str) + '\n')
    return results

