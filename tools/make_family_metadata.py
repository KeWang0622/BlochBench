#!/usr/bin/env python3
"""Write families/<id>/family.json from what each family already states (standard library only).

Every field is copied from one of three files of the family, and nothing else:

  README.md          domain name, tier, review status, time cap and the names of the automated checks
  instances.json     instance names, domain code, time cap in seconds and grader file
  task.example.json  id, split, scope and required outputs of the example instance

Where two files state the same fact (the time cap, the number of instances, the number of checks), they must agree.

  python3 tools/make_family_metadata.py           write every family.json
  python3 tools/make_family_metadata.py --check   exit 1 if a family.json is missing or differs from its sources

The format is defined by schemas/family.schema.json; tests/test_families.py checks both.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FAMILIES = REPO / "families"
SOURCES = ("README.md", "instances.json", "task.example.json")
COMMENT = (
    "Generated by tools/make_family_metadata.py from README.md, instances.json and task.example.json; "
    "edit those files and run make families."
)


class MetadataError(Exception):
    """A family whose files are missing a fact or state it inconsistently."""


def readme_line(readme: str, name: str, fid: str) -> str:
    """The value of a '- <name>: <value>' line of a family README."""
    match = re.search(rf"^- {re.escape(name)}:\s*(.+?)\s*$", readme, re.M)
    if not match:
        raise MetadataError(f"{fid}: README.md has no '- {name}:' line")
    return match.group(1)


def one_value(instances: list[dict], key: str, fid: str) -> object:
    """A field that must be the same in every instance of the family."""
    values = {json.dumps(x.get(key)) for x in instances}
    if len(values) != 1:
        raise MetadataError(f"{fid}: instances.json has different values of {key}: {sorted(values)}")
    return instances[0][key]


def required_outputs(task: dict, fid: str) -> list[str]:
    """required_outputs of task.example.json as a list of strings (the keys when it is an object of file names)."""
    outputs = task.get("required_outputs")
    if isinstance(outputs, dict):
        outputs = list(outputs)
    if not isinstance(outputs, list) or not outputs or not all(isinstance(o, str) for o in outputs):
        raise MetadataError(f"{fid}: task.example.json required_outputs must be a non-empty list or object")
    return outputs


def build(family_dir: Path) -> dict:
    """The family.json content of one family, derived from its README.md, instances.json and task.example.json."""
    fid = family_dir.name
    missing = [name for name in SOURCES if not (family_dir / name).is_file()]
    if missing:
        raise MetadataError(f"{fid}: missing {', '.join(missing)}")
    readme = (family_dir / "README.md").read_text(encoding="utf-8")
    instances = json.loads((family_dir / "instances.json").read_text(encoding="utf-8"))
    task = json.loads((family_dir / "task.example.json").read_text(encoding="utf-8"))

    title = re.search(r"^# (\S+)\s*$", readme, re.M)
    if not title or title.group(1) != fid:
        raise MetadataError(f"{fid}: the first heading of README.md must be the folder name")
    tier_line = readme_line(readme, "Tier", fid)
    tier = re.fullmatch(r"(\w+)(?: \((.+)\))?; review status: (.+)", tier_line)
    if not tier:
        raise MetadataError(f"{fid}: README.md Tier line is not '<tier> (<note>); review status: <status>'")
    cap = re.fullmatch(r"(\d+) min", readme_line(readme, "Time cap", fid))
    recorded = re.fullmatch(r"(\d+) \(instances\.json\)", readme_line(readme, "Instances recorded", fid))
    checks = re.search(r"^- Automated checks \((\d+)\):\s*(.+?)\s*$", readme, re.M)
    if not cap or not recorded or not checks:
        raise MetadataError(f"{fid}: README.md needs the Time cap, Instances recorded and Automated checks lines")
    check_names = [c.strip() for c in checks.group(2).split(",")]
    if len(check_names) != int(checks.group(1)) or len(set(check_names)) != len(check_names):
        raise MetadataError(f"{fid}: README.md names {len(check_names)} checks but counts {checks.group(1)}")

    if not isinstance(instances, list) or not instances:
        raise MetadataError(f"{fid}: instances.json must be a non-empty list")
    if len(instances) != int(recorded.group(1)):
        raise MetadataError(
            f"{fid}: README.md records {recorded.group(1)} instances, instances.json has {len(instances)}"
        )
    cap_s = one_value(instances, "cap_s", fid)
    if cap_s != 60 * int(cap.group(1)):
        raise MetadataError(
            f"{fid}: README.md time cap {cap.group(1)} min differs from cap_s {cap_s} in instances.json"
        )

    for key in ("id", "split", "scope"):
        if not isinstance(task.get(key), str) or not task[key]:
            raise MetadataError(f"{fid}: task.example.json needs a non-empty string {key}")
    return {
        "$schema": "../../schemas/family.schema.json",
        "$comment": COMMENT,
        "id": fid,
        "domain": one_value(instances, "domain", fid),
        "domain_name": readme_line(readme, "Domain", fid),
        "tier": tier.group(1),
        "tier_note": tier.group(2) or "",
        "review_status": tier.group(3),
        "time_cap_s": cap_s,
        "grader": one_value(instances, "grader", fid),
        "instances": [x["instance"] for x in instances],
        "checks": check_names,
        "example": {
            "task_id": task["id"],
            "split": task["split"],
            "scope": task["scope"],
            "required_outputs": required_outputs(task, fid),
        },
    }


def render(metadata: dict) -> str:
    """family.json text: one-space indentation (as in instances.json), non-ASCII kept, trailing newline."""
    return json.dumps(metadata, indent=1, ensure_ascii=False) + "\n"


def family_dirs(root: Path = FAMILIES) -> list[Path]:
    """Every family folder (a folder of families/ with an instances.json)."""
    return sorted(p.parent for p in root.glob("*/instances.json"))


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print(__doc__.strip().splitlines()[0], file=sys.stderr)
        print("usage: make_family_metadata.py [--check]", file=sys.stderr)
        return 2
    stale = []
    for family_dir in family_dirs():
        try:
            text = render(build(family_dir))
        except MetadataError as e:
            print(f"error: {e}", file=sys.stderr)
            return 1
        target = family_dir / "family.json"
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == text:
            continue
        stale.append(target.relative_to(REPO).as_posix())
        if not check:
            target.write_text(text, encoding="utf-8")
    if check and stale:
        print("out of date (run make families): " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{len(stale)} file(s) {'out of date' if check else 'written'}, {len(family_dirs())} families")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
